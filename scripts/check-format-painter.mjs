import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { Schema } from '@tiptap/pm/model';
import { EditorState, TextSelection } from '@tiptap/pm/state';
import { history, undo } from '@tiptap/pm/history';
import { captureTextFormat, paintTextFormat } from '../src/format-painter.mjs';

const attrs = { recordId: { default: null }, field: { default: 'zh' }, legacyStyle: { default: {} } };
const schema = new Schema({ nodes: { doc: { content: 'block+' }, paragraph: { group: 'block', content: 'inline*', attrs }, heading: { group: 'block', content: 'inline*', attrs: { ...attrs, level: { default: 1 } } }, text: { group: 'inline' } }, marks: { bold: {}, italic: {}, underline: {}, textStyle: { attrs: { color: { default: null }, fontSize: { default: null } } }, link: { attrs: { href: {} } } } });
const p = (text, marks = [], type = 'paragraph', legacyStyle = {}) => schema.nodes[type].create({ recordId: text, legacyStyle, level: 2 }, schema.text(text, marks));
const make = (nodes, from = 1, to = from) => { const doc = schema.nodes.doc.create(null, nodes); return EditorState.create({ doc, selection: TextSelection.create(doc, from, to), plugins: [history()] }); };
const select = (state, from, to) => state.apply(state.tr.setSelection(TextSelection.create(state.doc, from, to)));
const marks = [schema.marks.bold.create(), schema.marks.textStyle.create({ color: '#dc2626', fontSize: '24px' })];
let state = make([p('source', marks), p('target', [schema.marks.italic.create(), schema.marks.link.create({ href: 'https://example.org' })])], 1, 7);
const format = captureTextFormat(state);
state = select(state, 10, 13);
const original = state.doc, tr = state.tr;
assert.ok(paintTextFormat(format)({ state, tr, dispatch: () => {} })); state = state.apply(tr);
assert.equal(state.doc.textBetween(state.selection.from, state.selection.to), 'arg');
assert.ok(state.doc.rangeHasMark(10, 13, schema.marks.bold));
assert.ok(!state.doc.rangeHasMark(10, 13, schema.marks.italic));
assert.ok(state.doc.rangeHasMark(10, 13, schema.marks.link));
assert.ok(!state.doc.rangeHasMark(9, 10, schema.marks.bold));
let restored; assert.ok(undo(state, t => { restored = state.apply(t); })); assert.ok(restored.doc.eq(original));
const plain = captureTextFormat(make([p('plain')], 1, 6));
const clear = state.tr; paintTextFormat(plain)({ state, tr: clear, dispatch: () => {} }); state = state.apply(clear);
assert.ok(!state.doc.rangeHasMark(10, 13, schema.marks.bold));
assert.ok(!state.doc.rangeHasMark(10, 13, schema.marks.textStyle));
assert.ok(state.doc.rangeHasMark(10, 13, schema.marks.link));
const mixed = schema.nodes.paragraph.create(null, [schema.text('a', marks), schema.text('b', [schema.marks.bold.create(), schema.marks.textStyle.create({ color: '#dc2626', fontSize: '16px' })])]);
assert.deepEqual(captureTextFormat(make([mixed], 1, 3)).marks, [{ type: 'bold' }, { type: 'textStyle', attrs: { color: '#dc2626' } }]);
assert.equal(captureTextFormat(make([p('abc')])), null);
const heading = captureTextFormat(make([p('title', marks, 'heading')], 1, 6));
state = make([p('beforeTITLEafter')], 7, 12);
const headingTr = state.tr; paintTextFormat(heading)({ state, tr: headingTr, dispatch: () => {} }); state = state.apply(headingTr);
assert.deepEqual(state.doc.content.content.map(n => [n.type.name, n.textContent]), [['paragraph', 'before'], ['heading', 'TITLE'], ['paragraph', 'after']]);
assert.equal(state.doc.child(1).attrs.level, 2);
assert.ok(state.doc.child(1).firstChild.marks.some(m => m.type.name === 'bold'));
const legacy = make([p('old', [], 'paragraph', { size: 'text-lg' })], 1, 4);
assert.equal(captureTextFormat(legacy).marks[0].attrs.fontSize, '18px');
assert.deepEqual(captureTextFormat(legacy, { useLegacySize: false }).marks, []);
const report = { passed: ['partial format copy, exact target range and one-step undo', 'plain source clears character formatting while preserving target links', 'mixed source captures common attributes only', 'empty source ignored', 'heading format isolates selected target text', 'legacy sizes respect global typography override'] };
await fs.mkdir(new URL('../.local/checks/format-painter/', import.meta.url), { recursive: true });
await fs.writeFile(new URL('../.local/checks/format-painter/report.json', import.meta.url), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
