import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { documentFromRecords, recordsFromDocument, inlineText } from '../server/document-rich-text.mjs';

const record = (id, zh, en = '') => ({ id, type: 'text', data: { zh, en }, style: {}, attachments: [] });
const original = [record('a', '第一段', 'First'), record('b', '第二段', 'Second')];
const initial = documentFromRecords(original);
const firstPass = recordsFromDocument(initial, original);
assert.deepEqual(documentFromRecords(firstPass).content.map(node => inlineText(node.content)), ['第一段', 'First', '第二段', 'Second']);
const freelyOrdered = structuredClone(initial);
freelyOrdered.content = [initial.content[0], initial.content[2], initial.content[1], initial.content[3]];
const saved = recordsFromDocument(freelyOrdered, original);
assert.deepEqual(documentFromRecords(saved).content.map(node => inlineText(node.content)), ['第一段', '第二段', 'First', 'Second'], 'Independent paragraph order must survive serialization; no paired module reordering.');
const blank = { type: 'doc', content: [{ type: 'paragraph', attrs: { recordId: 'empty', field: 'zh' } }] };
const removedChinese = recordsFromDocument(blank, saved, 'zh');
assert.ok(removedChinese.some(item => item.data.en === 'First'));
const restoredChinese = recordsFromDocument(documentFromRecords(saved, 'zh'), removedChinese, 'zh');
assert.deepEqual(documentFromRecords(restoredChinese).content.filter(node => node.attrs?.recordId === 'a').map(node => node.attrs.field), ['zh', 'en']);
const marks = [{ type: 'text', text: '局部', marks: [{ type: 'bold' }, { type: 'textStyle', attrs: { color: '#dc2626', fontSize: '24px' } }] }, { type: 'text', text: '正文' }];
const rich = recordsFromDocument({ type: 'doc', content: [{ type: 'paragraph', attrs: { recordId: 'rich', field: 'zh' }, content: marks }] });
assert.deepEqual(documentFromRecords(rich).content[0].content, marks);
const oldFormatting = [{ ...record('old-style', '旧的整段加粗'), style: { weight: 'font-bold', decoration: 'underline', color: '#dc2626' } }];
const migratedFormatting = documentFromRecords(oldFormatting).content[0];
assert.ok(migratedFormatting.content[0].marks.some(mark => mark.type === 'bold'));
assert.equal(migratedFormatting.attrs.legacyStyle.weight, undefined, 'Legacy bold must become removable character formatting, not an unavoidable paragraph CSS rule.');
const translated = structuredClone(rich); translated[0].data.zh = '不同的译文';
assert.equal(inlineText(documentFromRecords(translated).content[0].content), '不同的译文', 'External text changes must invalidate stale character runs.');
const noEmptyEnglish = documentFromRecords([record('one', '只有中文')]);
assert.equal(noEmptyEnglish.content.length, 1, 'New paragraphs must not create artificial English module placeholders.');
const report = { passed: ['legacy bilingual import', 'free paragraph ordering roundtrip', 'hidden language preservation across delete/undo', 'partial character marks roundtrip', 'external text update invalidates old runs', 'no generated empty paired module'] };
const output = path.resolve(import.meta.dirname, '../.local/checks/rich-text-records'); await fs.mkdir(output, { recursive: true });
await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
