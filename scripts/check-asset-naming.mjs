import assert from 'node:assert/strict';
import {normalizeAssetName,enrichAssetRows,makeAssetExportPlan} from '../server/ue-asset-naming.mjs';
assert.equal(normalizeAssetName('SM_T_Icon（Blue）',{assetClass:'Texture2D'}),'T_Icon_Blue');
assert.equal(normalizeAssetName('Palm Mesh',{assetClass:'StaticMesh'}),'SM_Palm_Mesh');
assert.equal(normalizeAssetName('BP_BP_Grab',{assetClass:'Blueprint',recommendedPrefix:'AC_'}),'AC_Grab');
const assets=[{packageName:'/Game/Map_BuiltData',assetClass:'MapBuildDataRegistry'},{packageName:'/Game/Map',assetClass:'World',recommendedPrefix:'L_'},{packageName:'/Game/Icon',assetClass:'Texture2D'}];
const rows=assets.map(a=>({entryKey:a.packageName,owner:a.packageName,kind:'资源',group:'assets',translated:a.packageName.split('/').pop()}));
const moves=makeAssetExportPlan(rows,assets,'Pack');
assert.equal(moves[0].assetClass,'World');
assert.equal(moves.find(m=>m.assetClass==='MapBuildDataRegistry').newPath,'/Game/Pack/L_Map_BuiltData');
assert.equal(moves.find(m=>m.assetClass==='Texture2D').newName,'T_Icon');
assert.equal(enrichAssetRows(rows,assets)[2].requiredPrefix,'T_');
const chinese=[{...rows[2],translated:'图标'}];
assert.throws(()=>makeAssetExportPlan(chinese,[assets[2]],'Pack'),/命名无效/);
assert.equal(makeAssetExportPlan(chinese,[assets[2]],'Pack',{direction:'en-zh'})[0].newName,'T_图标');
const duplicate=[assets[2],{...assets[2],packageName:'/Game/Other'}];
assert.throws(()=>makeAssetExportPlan([rows[2],{...rows[2],owner:'/Game/Other',translated:'Icon'}],duplicate,'Pack'),/重名/);
assert.equal(rows[2].translated,'Icon','planning never mutates the review input');
console.log('Asset type prefixes, map data pairing, learning direction and collision checks passed.');
