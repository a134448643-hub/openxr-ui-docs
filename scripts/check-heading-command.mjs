import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { Schema } from '@tiptap/pm/model';
import { EditorState, TextSelection } from '@tiptap/pm/state';
import { history, undo } from '@tiptap/pm/history';
import { applySelectedHeading } from '../src/heading-command.mjs';
import { documentFromRecords, recordsFromDocument } from '../server/document-rich-text.mjs';

const attrs = { recordId: { default: null }, field: { default: 'zh' }, legacyStyle: { default: {} } };
const schema = new Schema({ nodes: { doc: { content: 'block+' }, paragraph: { group: 'block', content: 'inline*', attrs }, heading: { group: 'block', content: 'inline*', attrs: { ...attrs, level: { default: 1 } } }, image: { group: 'block', atom: true }, text: { group: 'inline' } }, marks: { bold: {} } });
const p = (text, id = 'a', field = 'zh') => schema.nodes.paragraph.create({ recordId: id, field }, text ? schema.text(text) : null);
const make = (nodes, from, to = from) => { const doc = schema.nodes.doc.create(null, nodes); return EditorState.create({ doc, selection: TextSelection.create(doc, from, to), plugins: [history()] }); };
const run = (state, level, options) => { const tr = state.tr; assert.ok(applySelectedHeading(level, options)({ state, tr, dispatch: () => {} })); return state.apply(tr); };
let state = make([p('前文标题正文')], 3, 5);
const original = state.doc;
state = run(state, 1);
assert.deepEqual(state.doc.content.content.map(node => [node.type.name, node.textContent]), [['paragraph','前文'], ['heading','标题'], ['paragraph','正文']]);
assert.equal(state.doc.textBetween(state.selection.from, state.selection.to), '标题');
assert.equal(new Set(state.doc.content.content.map(node => node.attrs.recordId)).size, 3);
let restored; assert.ok(undo(state, tr => { restored = state.apply(tr); })); assert.ok(restored.doc.eq(original));
state = run(make([p('前文正文')], 3), 2);
assert.deepEqual(state.doc.content.content.map(node => [node.type.name,node.textContent]), [['paragraph','前文'], ['heading',''], ['paragraph','正文']]);
assert.equal(state.selection.$from.parent.type.name, 'heading');
state = run(make([p('完整标题')], 1, 5), 3);
assert.equal(state.doc.childCount, 1); assert.equal(state.doc.firstChild.attrs.level, 3);
state = run(make([p('正文')], 1), 1);
assert.equal(state.doc.firstChild.type.name, 'heading'); assert.equal(state.doc.child(1).textContent, '正文');
state = run(make([p('正文')], 3), 1);
assert.equal(state.doc.lastChild.type.name, 'heading'); assert.equal(state.doc.firstChild.textContent, '正文');
state = run(make([p('')], 1), 1); assert.equal(state.doc.childCount, 1);
state = run(make([p('开始内容'), schema.nodes.image.create(), p('结束正文','b')], 3, 11), 1);
assert.equal(state.doc.child(2).type.name, 'image');
assert.deepEqual(state.doc.content.content.filter(node => node.type.name === 'heading').map(node => node.textContent), ['内容', '结束正']);
const bilingual = [{ id:'a',type:'text',data:{zh:'中文标题',en:'English body'},style:{},attachments:[] }];
state = run(make([p('中文标题')],1,5),1);
const records = recordsFromDocument(state.doc.toJSON(),bilingual,'zh');
const reopened = documentFromRecords(records,'bilingual');
assert.equal(reopened.content.find(node=>node.attrs.field==='zh').type,'heading');
assert.equal(reopened.content.find(node=>node.attrs.field==='en').type,'paragraph');
const marked = schema.nodes.paragraph.create({recordId:'marked'},[schema.text('前'),schema.text('标题',[schema.marks.bold.create()]),schema.text('后')]);
state=run(make([marked],2,4),1);assert.equal(state.doc.child(1).firstChild.marks[0].type.name,'bold');
const report={passed:['selection isolates heading and keeps surrounding body','one-step undo','empty heading insertion at start/middle/end and empty paragraph','multi-paragraph selection preserves image','bilingual paragraph types roundtrip independently','inline marks survive heading split']};
await fs.mkdir(new URL('../.local/checks/heading-command/',import.meta.url),{recursive:true});
await fs.writeFile(new URL('../.local/checks/heading-command/report.json',import.meta.url),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
